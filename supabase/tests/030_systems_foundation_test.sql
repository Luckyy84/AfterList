begin;
select no_plan();
select ok(not has_function_privilege('authenticated', 'public.consume_account_reauth_attempt(uuid)', 'execute'), 'clients cannot bypass reauth throttling');
select ok(not has_function_privilege('anon', 'public.consume_account_reauth_attempt(uuid)', 'execute'), 'anonymous cannot consume account limits');
select ok(has_function_privilege('service_role', 'public.consume_account_reauth_attempt(uuid)', 'execute'), 'account server may consume limits');
select ok(not has_table_privilege('authenticated', 'private.account_reauth_attempts', 'select'), 'reauth attempts are private');
select ok(not has_table_privilege('anon', 'public.api_tokens', 'select'), 'token hashes never exposed');
select ok(not has_table_privilege('authenticated', 'public.api_tokens', 'insert'), 'token scopes cannot bypass API validation');
select ok(not exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r' and not c.relrowsecurity), 'all public tables use RLS');
insert into auth.users(id) values ('e0000000-0000-0000-0000-000000000001');
select ok(public.consume_account_reauth_attempt('e0000000-0000-0000-0000-000000000001'), 'first reauth allowed');
select public.consume_account_reauth_attempt('e0000000-0000-0000-0000-000000000001') from generate_series(1,4);
select ok(not public.consume_account_reauth_attempt('e0000000-0000-0000-0000-000000000001'), 'sixth attempt blocked');
update private.account_reauth_attempts set window_started_at = now() - interval '16 minutes';
select ok(public.consume_account_reauth_attempt('e0000000-0000-0000-0000-000000000001'), 'expired window resets');
delete from auth.users where id='e0000000-0000-0000-0000-000000000001';
select is((select count(*) from private.account_reauth_attempts), 0::bigint, 'account deletion cascades reauth state');
select * from finish();
rollback;
